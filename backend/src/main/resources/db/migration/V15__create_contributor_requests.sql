-- Peticiones de usuarios comunes para ser promovidos a CONTRIBUTOR (Grow). Quedan visibles para
-- todo el staff (MODERATOR+), que las aprueba (promueve) o rechaza. Guardamos el historial completo:
-- mensaje, método de contacto, estado, y quién/cuándo resolvió.
CREATE TABLE contributor_requests (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_user_id    BIGINT NOT NULL REFERENCES users (id),
    message              TEXT NOT NULL,
    contact              VARCHAR(200) NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at          TIMESTAMP(6) WITH TIME ZONE,
    resolved_by_user_id  BIGINT REFERENCES users (id)
);

-- La bandeja del staff lista por estado, ordenada por fecha; el badge cuenta pendientes.
CREATE INDEX idx_contributor_requests_status ON contributor_requests (status, created_at DESC);
-- El historial propio del solicitante se consulta por requester.
CREATE INDEX idx_contributor_requests_requester ON contributor_requests (requester_user_id, created_at DESC);
-- Anti-duplicados: un usuario no puede tener más de una petición PENDING a la vez.
CREATE UNIQUE INDEX uq_contributor_requests_pending
    ON contributor_requests (requester_user_id) WHERE status = 'PENDING';
