-- Verificación de email + tokens de un solo uso (verificación de email y recuperación de contraseña).

-- Los usuarios EXISTENTES quedan verificados (para no bloquearlos); los nuevos registros arrancan
-- en false y deben verificar su email antes de poder iniciar sesión.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE users SET email_verified = TRUE;

-- Se guarda el HASH (SHA-256 en hex) del token, nunca el token en claro: si se filtra la base,
-- los links enviados por email no son utilizables. El token en claro viaja solo en el email.
CREATE TABLE user_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    purpose    VARCHAR(30) NOT NULL,   -- EMAIL_VERIFICATION | PASSWORD_RESET
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE
);

-- Búsqueda del token al validarlo (por su hash).
CREATE UNIQUE INDEX uq_user_tokens_hash ON user_tokens (token_hash);
-- Invalidación de tokens previos del mismo usuario y propósito al emitir uno nuevo.
CREATE INDEX idx_user_tokens_user_purpose ON user_tokens (user_id, purpose);
