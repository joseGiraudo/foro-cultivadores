-- Notificaciones in-app. Guardamos snapshots del nombre del actor y el título del post para
-- no hacer joins ni acoplar módulos al leer la lista (son datos point-in-time de todos modos).
CREATE TABLE notifications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES users (id),
    actor_user_id     BIGINT NOT NULL REFERENCES users (id),
    actor_username    VARCHAR(30) NOT NULL,
    type              VARCHAR(30) NOT NULL,
    post_id           BIGINT NOT NULL REFERENCES posts (id),
    post_title        VARCHAR(150) NOT NULL,
    comment_id        BIGINT REFERENCES comments (id),
    is_read           BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- La bandeja se consulta por destinatario, ordenada por fecha desc; el badge cuenta no leídas.
CREATE INDEX idx_notifications_recipient ON notifications (recipient_user_id, created_at DESC);
CREATE INDEX idx_notifications_unread ON notifications (recipient_user_id) WHERE is_read = FALSE;
